"""Check the local project against DRIVE_MANIFEST.tsv (the Google Drive snapshot).

* Every file marked "included" must exist with the recorded size and SHA-256.
* Files marked "NOT INCLUDED" (over the 10 MB download limit) are listed with
  their Drive links.  No LeukemiPrediag v2 code reads them; they are cBioPortal
  expression / methylation / CNA matrices and one AlphaMissense subset.

Exit code 0 = all included files intact; 1 = something missing or changed.

    python scripts/check_data.py
"""
from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "DRIVE_MANIFEST.tsv"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    rows = list(csv.DictReader(open(MANIFEST, encoding="utf-8"), delimiter="\t"))
    seen, bad, ok, large_present, large_missing = set(), [], 0, [], []
    for r in rows:
        path = ROOT / r["local_path"]
        status = r["status"]
        if status.startswith("duplicate"):
            continue
        if status.startswith("NOT INCLUDED"):
            (large_present if path.exists() else large_missing).append(r)
            continue
        if r["local_path"] in seen:
            continue
        seen.add(r["local_path"])
        if not path.exists():
            bad.append(f"MISSING  {r['local_path']}")
        elif path.stat().st_size != int(r["size_bytes"]) or sha256(path) != r["sha256"]:
            bad.append(f"CHANGED  {r['local_path']}")
        else:
            ok += 1
    print(f"Drive snapshot files intact: {ok}/{len(seen)}")
    for line in bad:
        print("  " + line)
    if large_missing:
        mb = sum(int(r["size_bytes"]) for r in large_missing) / 1e6
        print(f"\nOptional large files not present ({len(large_missing)}, {mb:.0f} MB). "
              "Not used by the v2 pipeline; download from Drive only if you need them:")
        for r in large_missing:
            print(f"  {int(r['size_bytes'])/1e6:7.1f} MB  {r['local_path']}\n             {r['drive_link']}")
    if large_present:
        print(f"\nOptional large files present: {len(large_present)}")
    if bad:
        print("\nNOTE: 'CHANGED' is expected for outputs you regenerated by re-running notebooks.")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
